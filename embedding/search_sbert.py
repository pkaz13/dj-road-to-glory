import numpy as np
import json
import os
import time
from sentence_transformers import SentenceTransformer
from sklearn.metrics.pairwise import cosine_similarity
from config import (
    OUTPUT_DIR,
    OUTPUT_SBERT_EMBEDDINGS_FILE,
    OUTPUT_SBERT_SENTENCES_MAP_FILE,
)

# --- CONFIGURATION ---
MODEL_NAME = "intfloat/multilingual-e5-small"
EMBEDDINGS_FILE = os.path.join(OUTPUT_DIR, OUTPUT_SBERT_EMBEDDINGS_FILE)
SENTENCES_MAP_FILE = os.path.join(OUTPUT_DIR, OUTPUT_SBERT_SENTENCES_MAP_FILE)


def load_resources():
    """Loads model, vectors and sentences."""
    print("Loading resources...")

    # 1. Checking files
    if not os.path.exists(EMBEDDINGS_FILE) or not os.path.exists(SENTENCES_MAP_FILE):
        raise FileNotFoundError(
            "Missing files generated by 'generate-sbert.py' script."
        )

    # 2. Loading corpus vectors
    corpus_embeddings = np.load(EMBEDDINGS_FILE)

    # 3. Loading sentences (index -> sentence)
    with open(SENTENCES_MAP_FILE, "r", encoding="utf-8") as f:
        sentences = json.load(f)

    # 4. Loading model (needed to encode query)
    model = SentenceTransformer(MODEL_NAME)

    print(f"Resources loaded. Number of sentences in the database: {len(sentences)}")
    return model, corpus_embeddings, sentences


def search(query, model, corpus_embeddings, sentences, top_k=5):
    """Searches for the most similar sentences to the query."""

    # Encoding query to vector
    query_embedding = model.encode([query], convert_to_numpy=True)

    # Calculating similarity (Cosine Similarity)
    # Result is an array of similarities for each sentence in the database
    similarities = cosine_similarity(query_embedding, corpus_embeddings)[0]

    # Getting indices of top_k best results
    # argsort sorts in ascending order, so we take the end ([::-1])
    top_indices = np.argsort(similarities)[::-1][:top_k]

    results = []
    for idx in top_indices:
        score = similarities[idx]
        text = sentences[idx]
        results.append((score, text))

    return results


# --- MAIN LOOP OF THE PROGRAM ---
if __name__ == "__main__":
    try:
        # Initialization (one-time)
        model, db_vectors, db_sentences = load_resources()

        print("\n--- SEMANTIC SEARCH SYSTEM (SBERT) ---")
        print("Enter a sentence to find similar in the corpus.")
        print("Enter 'exit' or 'q' to exit.\n")

        while True:
            query = input("Query: ")
            if query.lower() in ["exit", "q"]:
                break

            if not query.strip():
                continue

            start_t = time.time()
            results = search(query, model, db_vectors, db_sentences, top_k=5)
            end_t = time.time()

            print(f"\nResults (time: {end_t - start_t:.3f}s):")
            for score, text in results:
                print(f"  [{score:.4f}] {text}")
            print("-" * 40)

    except Exception as e:
        print(f"\nERROR: {e}")
        print("Make sure you first ran the generating script!")
